CREATE OR REPLACE VIEW TICAN.VW_PRODUCTS_X_SUBSTANCES
AS
SELECT P.*, S.SUBSTANCE, S.STATUS AS SUBSTANCE_STATUS
FROM
TICAN.TB_PRODUCTS P
INNER JOIN TICAN.TB_SUBSTANCES S
ON P.ID_SUBSTANCE = S.PK_SUBSTANCE;
