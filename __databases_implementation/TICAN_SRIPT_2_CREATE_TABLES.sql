CREATE OR REPLACE TRIGGER TICAN.TRG_PRODUCTS_BEFORE_INSERT
BEFORE INSERT
   ON TICAN.TB_PRODUCTS
   FOR EACH ROW
DECLARE
   v_NEW_ID NUMBER;
BEGIN
   SELECT TICAN.SQ_TICAN.NEXTVAL INTO v_NEW_ID
   FROM DUAL;

   :NEW.PK_PRODUCT:= v_NEW_ID;

   :NEW.DT_INSERT:= SYSDATE;
   :NEW.DT_UPDATE:= SYSDATE;
   :NEW.USER_CODE:= 'tican_user';
   
END;
--
CREATE OR REPLACE TRIGGER TICAN.TRG_SUBSTANCES_BEFORE_INSERT
BEFORE INSERT
  ON TICAN.TB_SUBSTANCES
  FOR EACH ROW
DECLARE
v_NEW_ID NUMBER;
BEGIN
   SELECT TICAN.SQ_TICAN.NEXTVAL INTO v_NEW_ID
   FROM DUAL;
  
  :NEW.PK_SUBSTANCE:= v_NEW_ID;
  :NEW.STATUS:= 'inactive';
  
END;
